# /// script
# requires-python = ">=3.12,<3.13"
# dependencies = [
#   "umap-learn>=0.5,<0.6",
#   "numpy>=1.26,<3",
#   "duckdb>=1,<2",
# ]
# ///
"""price_transform.py — what out-of-sample placement (`UMAP.transform`) actually costs,
against the real corpus `measure.py`'s full-refit run already used.

`umap-learn`'s `UMAP.transform(X)` is public in the pinned bound (>=0.5,<0.6,
resolved 0.5.12 here), and places new rows into an existing embedding without moving
the rows already in it. This script calls it and prices what that costs.

Reuses `eval/map-refit-stability/build/`'s own embedded Parquets from `measure.py`'s
last run (`control_A_embedded.parquet` — the 3,000-row base — and
`append_{05,20,50}_embedded.parquet` — base + appended rows) so the fitted UMAP model
and the comparison are against the identical vectors this eval's headline numbers came
from, not a fresh sample. Run `uv run eval/map-refit-stability/measure.py` first if
`build/` is not there — it is gitignored, intermediate, and regenerated by that
script.

FOUR THINGS THIS PRICES:

1. MODEL PERSISTENCE SIZE. `.transform()` needs the FITTED reducer object, not just
   its output coordinates — the fit (the k-NN graph, the optimised embedding, the
   internal state `transform` walks) has to survive between the process that ran
   `fit()` and the process that later runs `transform()` on new rows, since this
   operator is a fresh `uv run` per invocation with nothing else persisted. Pickled
   and measured on disk.

2. WHETHER THE BASE ROWS ACTUALLY STAY PUT. `reducer.embedding_` is captured right
   after `fit()` and compared, by max absolute difference, to `reducer.embedding_`
   after every `.transform()` call below — measured, not assumed from
   `.transform()`'s documented contract.

3. PLACEMENT FIDELITY AGAINST A CEILING, not against 1.0. A 2D map cannot recover
   every neighbour a 256-d embedding space has — this operator's own README already
   measures that loss for a stable corpus (34.9% at k=10 on a different corpus). So
   fidelity here is read against the SAME corpus's own ceiling: how much of a BASE
   row's 256-d neighbourhood its OWN base fit recovers, at the same k=20 used
   throughout. Two numbers are then read against that ceiling, both scored against
   the 256-d embeddings as ground truth (cosine, k=20, base rows as the candidate
   pool in every case) rather than against each other — a full refit's placement of
   a NEW row, and `.transform()`'s placement of the same row. Comparing a
   full-refit-of-new-rows fidelity number against a base-row CHURN number (the
   headline table above) would be comparing two different queries against two
   different references; this does not do that.

   SELF-CHECKS GUARD THIS FROM SILENTLY BREAKING, and they live in
   `placement_bounds.py` rather than here, because a bound only this file asserts is a
   bound nothing observes until someone re-runs this file. `check_findings.py` applies
   the same functions to the committed JSON on every CI run. Three shapes are caught:
   a fidelity far below the ceiling (swapping the full refit's own base coordinates for
   the ORIGINAL base fit's, a real mistake made once while writing this script, drops it
   to near zero); a fidelity above the ceiling, which is what a query compared against
   itself reads; and the two arms coming back as the SAME number, which is what scoring
   `.transform()`'s rows against the full refit's own base pool produces and which sits
   comfortably inside the ceiling window at every fraction. See that file for why the
   third bound is not `transform < full_refit`.

4. RAW DISPLACEMENT, reported but not the fidelity claim: UMAP's frame is arbitrary
   up to rotation/reflection/rescaling between two INDEPENDENT fits (the same reason
   the headline table above normalises rather than aligning), so a raw distance
   between where `.transform()` and a full refit put the same row mixes genuine
   placement error with the fact that the two frames are unrelated.

Run: `uv run eval/map-refit-stability/price_transform.py`. Writes
`transform_pricing.json` beside this file.
"""
from __future__ import annotations

import json
import pickle
import sys
import time
from pathlib import Path

import duckdb
import numpy as np
import umap

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"

# The bounds live beside this file, stdlib-only, so CI can apply them to the committed
# JSON without `uv`. Imported by path rather than assumed to be on sys.path, because
# `uv run` may be invoked from anywhere in the tree.
sys.path.insert(0, str(HERE))
import placement_bounds  # noqa: E402

APPEND_FRACTIONS = ("append_05", "append_20", "append_50")
K_NEIGHBOURS = 20



def load_embeddings(parquet: Path) -> tuple[list[str], np.ndarray]:
    con = duckdb.connect()
    rows = con.execute(
        f"SELECT name, embedding FROM read_parquet('{parquet.as_posix()}')"
    ).fetchall()
    names = [r[0] for r in rows]
    vectors = np.array([r[1] for r in rows], dtype=np.float64)
    return names, vectors


def load_xy(parquet: Path) -> dict[str, tuple[float, float]]:
    con = duckdb.connect()
    rows = con.execute(
        f"SELECT name, projection_x, projection_y FROM read_parquet('{parquet.as_posix()}')"
    ).fetchall()
    return {name: (x, y) for name, x, y in rows}


def nearest_indices_euclidean(
    query_coords: np.ndarray, pool_coords: np.ndarray, k: int, exclude_self: bool
) -> np.ndarray:
    """Each query row's k nearest pool rows by Euclidean distance. `exclude_self`
    is for the case where query and pool are the SAME rows, in the SAME order — the
    ceiling computation below — so a row is not its own nearest neighbour."""
    diff = pool_coords[None, :, :] - query_coords[:, None, :]
    dist = np.sqrt((diff**2).sum(axis=-1))
    if exclude_self:
        np.fill_diagonal(dist, np.inf)
    return np.argsort(dist, axis=1)[:, :k]


def nearest_indices_cosine(
    query_vectors: np.ndarray, pool_vectors: np.ndarray, k: int, exclude_self: bool
) -> np.ndarray:
    """Each query row's k nearest pool rows by cosine distance — the metric this
    operator actually projects with. Vectors are normalised here rather than assumed
    already unit-length, so this is correct regardless of the caller's embedding
    step."""
    q_norm = query_vectors / np.linalg.norm(query_vectors, axis=1, keepdims=True)
    p_norm = pool_vectors / np.linalg.norm(pool_vectors, axis=1, keepdims=True)
    similarity = q_norm @ p_norm.T
    dist = 1.0 - similarity
    if exclude_self:
        np.fill_diagonal(dist, np.inf)
    return np.argsort(dist, axis=1)[:, :k]


def overlap_fractions(nn_a: np.ndarray, nn_b: np.ndarray, k: int) -> np.ndarray:
    return np.array(
        [len(set(nn_a[i]) & set(nn_b[i])) / k for i in range(nn_a.shape[0])]
    )


def main() -> int:
    base_parquet = BUILD / "control_A_embedded.parquet"
    if not base_parquet.is_file():
        raise SystemExit(
            f"{base_parquet} is missing — run "
            "`uv run eval/map-refit-stability/measure.py` first to populate build/."
        )

    base_names, base_vectors = load_embeddings(base_parquet)
    print(f"[price] base: {len(base_names)} rows, {base_vectors.shape[1]}-d", file=sys.stderr)

    t0 = time.time()
    reducer = umap.UMAP(
        n_components=2,
        n_neighbors=15,
        min_dist=0.1,
        metric="cosine",
        random_state=42,
        verbose=False,
    )
    base_coords = reducer.fit_transform(base_vectors)
    fit_seconds = time.time() - t0
    print(f"[price] fit in {fit_seconds:.1f}s", file=sys.stderr)
    embedding_after_fit = reducer.embedding_.copy()

    pickle_path = BUILD / "fitted_reducer.pkl"
    with open(pickle_path, "wb") as f:
        pickle.dump(reducer, f)
    pickle_bytes = pickle_path.stat().st_size
    print(f"[price] pickled reducer: {pickle_bytes:,} bytes", file=sys.stderr)

    # The scale to normalise raw displacement against, matching measure.py's own —
    # the base map's median nearest-neighbour spacing.
    diff = base_coords[:, None, :] - base_coords[None, :, :]
    dist = np.sqrt((diff**2).sum(axis=-1))
    np.fill_diagonal(dist, np.inf)
    scale = float(np.median(dist.min(axis=1)))

    k = min(K_NEIGHBOURS, len(base_names) - 1)

    # THE CEILING: how much of a BASE row's own 256-d neighbourhood its own base fit
    # recovers, at the same k used throughout. Everything below is read against this,
    # not against 1.0.
    ceiling_256d_nn = nearest_indices_cosine(base_vectors, base_vectors, k, exclude_self=True)
    ceiling_2d_nn = nearest_indices_euclidean(base_coords, base_coords, k, exclude_self=True)
    ceiling_fractions = overlap_fractions(ceiling_256d_nn, ceiling_2d_nn, k)
    ceiling = float(ceiling_fractions.mean())
    print(f"[price] corpus ceiling (base rows, 2D vs 256-d, k={k}): {ceiling:.3f}", file=sys.stderr)

    base_name_set = set(base_names)
    results = {
        "base_rows": len(base_names),
        "umap_params": {"metric": "cosine", "neighbors": 15, "min_dist": 0.1, "seed": 42},
        "fit_seconds": round(fit_seconds, 1),
        "pickled_reducer_bytes": pickle_bytes,
        "base_map_median_nn_spacing": scale,
        "base_rows_moved_by_transform": None,
        "knn_overlap_k": k,
        "corpus_ceiling_256d_vs_2d": ceiling,
        "placements": {},
    }

    max_embedding_drift = 0.0

    for tag in APPEND_FRACTIONS:
        embedded = BUILD / f"{tag}_embedded.parquet"
        projected = BUILD / f"{tag}_projected.parquet"
        if not embedded.is_file() or not projected.is_file():
            print(f"[price] skipping {tag}: {embedded} or {projected} missing", file=sys.stderr)
            continue

        all_names, all_vectors = load_embeddings(embedded)
        new_indices = [i for i, n in enumerate(all_names) if n not in base_name_set]
        new_names = [all_names[i] for i in new_indices]
        new_vectors = all_vectors[new_indices]

        t0 = time.time()
        placed = reducer.transform(new_vectors)
        transform_seconds = time.time() - t0

        # §2: does `.transform()` actually leave the fitted embedding untouched?
        drift = float(np.max(np.abs(reducer.embedding_ - embedding_after_fit)))
        max_embedding_drift = max(max_embedding_drift, drift)

        # Determinism check: transform the same rows twice and confirm agreement,
        # matching the control the headline measurement above already established
        # for a full refit.
        placed_again = reducer.transform(new_vectors)
        transform_repeat_max_abs_diff = float(np.max(np.abs(placed - placed_again)))

        full_refit_xy = load_xy(projected)
        base_coords_in_full_refit = np.array([full_refit_xy[n] for n in base_names])
        true_new_coords = np.array([full_refit_xy[n] for n in new_names])

        # §3: fidelity against the 256-d ground truth, for both placements, using
        # the SAME base-row candidate pool and the SAME k as the ceiling above.
        truth_nn = nearest_indices_cosine(new_vectors, base_vectors, k, exclude_self=False)
        transform_2d_nn = nearest_indices_euclidean(placed, base_coords, k, exclude_self=False)
        full_refit_2d_nn = nearest_indices_euclidean(
            true_new_coords, base_coords_in_full_refit, k, exclude_self=False
        )
        transform_vs_truth = overlap_fractions(truth_nn, transform_2d_nn, k)
        full_refit_vs_truth = overlap_fractions(truth_nn, full_refit_2d_nn, k)

        full_refit_vs_truth_mean = float(full_refit_vs_truth.mean())
        transform_vs_truth_mean = float(transform_vs_truth.mean())

        # The bounds, from placement_bounds.py — the same functions check_findings.py
        # applies to the committed JSON in CI. Asserted here so a broken measurement
        # stops before its numbers are written, and there so one that already was
        # written stops before it is believed.
        breaches = placement_bounds.ceiling_problems(
            tag, "full-refit", full_refit_vs_truth_mean, ceiling
        ) + placement_bounds.ceiling_problems(
            tag, "transform", transform_vs_truth_mean, ceiling
        ) + placement_bounds.separation_problems(
            tag, transform_vs_truth_mean, full_refit_vs_truth_mean
        )
        assert not breaches, "\n".join(breaches)

        # Frame-invariant fidelity between the two PLACEMENTS themselves — not read
        # against the ceiling, since neither side of it is the 256-d truth.
        placement_nn_transform = nearest_indices_euclidean(placed, base_coords, k, exclude_self=False)
        placement_nn_full_refit = nearest_indices_euclidean(
            true_new_coords, base_coords_in_full_refit, k, exclude_self=False
        )
        transform_vs_full_refit = overlap_fractions(placement_nn_transform, placement_nn_full_refit, k)

        disp = np.sqrt(((placed - true_new_coords) ** 2).sum(axis=1))

        results["placements"][tag] = {
            "new_rows": len(new_names),
            "transform_seconds": round(transform_seconds, 2),
            "transform_repeat_max_abs_diff": transform_repeat_max_abs_diff,
            "transform_vs_256d_truth_mean": float(transform_vs_truth.mean()),
            "full_refit_vs_256d_truth_mean": full_refit_vs_truth_mean,
            "transform_vs_full_refit_placement_mean": float(transform_vs_full_refit.mean()),
            "raw_displacement_vs_full_refit_mean": float(disp.mean()),
            "raw_displacement_vs_full_refit_normalised_mean": float(disp.mean() / scale),
        }
        print(
            f"[price] {tag}: {len(new_names)} new rows — vs 256-d truth: "
            f"transform={transform_vs_truth.mean():.3f} full_refit={full_refit_vs_truth.mean():.3f} "
            f"(ceiling {ceiling:.3f})",
            file=sys.stderr,
        )

    results["base_rows_moved_by_transform"] = max_embedding_drift
    print(f"[price] max embedding drift from any transform() call: {max_embedding_drift}", file=sys.stderr)

    out = HERE / "transform_pricing.json"
    out.write_text(json.dumps(results, indent=2) + "\n")
    print(f"[price] wrote {out}", file=sys.stderr)
    print(json.dumps(results, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
