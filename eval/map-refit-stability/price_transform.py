# /// script
# requires-python = ">=3.12,<3.13"
# dependencies = [
#   "umap-learn>=0.5,<0.6",
#   "numpy>=1.26,<3",
#   "duckdb>=1,<2",
# ]
# ///
"""price_transform.py — what out-of-sample placement (`UMAP.transform`) actually costs,
against the real corpus this card already measured a full refit against.

Round three of this card's review found `operators/umap_project/README.md` eliminating
"pin the projection and place new points approximately" on the claim that
`umap-learn`'s public API is fit-only. It is not: `UMAP.transform(X)` is public in the
pinned bound (>=0.5,<0.6, resolved 0.5.12 here), and places new rows into an existing
embedding without moving the rows already in it. That claim was inherited from the
card's `Evidence:` line about a DIFFERENT library (Apple's Rust UMAP, which genuinely
is fit-only) and generalised to umap-learn without running `dir(umap.UMAP)`. This
script is the correction: actually call `.transform()` and price what it costs rather
than asserting it does not exist.

Reuses `eval/map-refit-stability/build/`'s own embedded Parquets from `measure.py`'s
last run (`control_A_embedded.parquet` — the 3,000-row base — and
`append_{05,20,50}_embedded.parquet` — base + appended rows) so the fitted UMAP model
and the comparison are against the identical vectors the card's headline numbers came
from, not a fresh sample. Run `uv run eval/map-refit-stability/measure.py` first if
`build/` is not there — it is gitignored, intermediate, and regenerated by that
script.

THREE THINGS THIS PRICES, matching what round three asked for:

1. MODEL PERSISTENCE SIZE. `.transform()` needs the FITTED reducer object, not just
   its output coordinates — the fit (the k-NN graph, the optimised embedding, the
   internal state `transform` walks) has to survive between the process that ran
   `fit()` and the process that later runs `transform()` on new rows, since this
   operator is a fresh `uv run` per invocation with nothing else persisted. Pickled
   and measured on disk.

2. PLACEMENT FIDELITY, measured the way this card's own headline number is measured
   and for the same reason: UMAP's coordinate frame is arbitrary up to
   rotation/reflection/rescaling between two INDEPENDENT fits, so a raw Euclidean
   distance between "where `.transform()` put a new row" and "where a full refit put
   the same row" mixes two things — genuine placement error, and the fact that a full
   refit lands in a different, unrelated frame altogether (the same reason this card's
   headline table normalises and does not Procrustes-align displacement between two
   refits). `.transform()`'s output lives in the SAME frame as the base fit by
   construction; a full refit's does not. So fidelity here is the frame-invariant
   measure already used for the headline number: for each newly placed row, its 20
   nearest neighbours AMONG THE BASE ROWS in the transform's frame, against its 20
   nearest neighbours among the base rows (as they sit in that fit) in the full
   refit's frame. Raw displacement is reported too, but it is expected to be large
   for the frame reason above and is not the fidelity claim.

3. WHETHER THE BASE ROWS ACTUALLY STAY PUT. Not measured — guaranteed by
   `.transform()`'s own contract (it does not re-optimise the training embedding) —
   but confirmed here by never calling `fit_transform` on the combined table.

Run: `uv run eval/map-refit-stability/price_transform.py`. Writes
`transform_pricing.json` beside this file.
"""
from __future__ import annotations

import json
import pickle
import sys
import time
from pathlib import Path

import duckdb
import numpy as np
import umap

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"

APPEND_FRACTIONS = ("append_05", "append_20", "append_50")
K_NEIGHBOURS = 20


def load_embeddings(parquet: Path) -> tuple[list[str], np.ndarray]:
    con = duckdb.connect()
    rows = con.execute(
        f"SELECT name, embedding FROM read_parquet('{parquet.as_posix()}')"
    ).fetchall()
    names = [r[0] for r in rows]
    vectors = np.array([r[1] for r in rows], dtype=np.float64)
    return names, vectors


def load_xy(parquet: Path) -> dict[str, tuple[float, float]]:
    con = duckdb.connect()
    rows = con.execute(
        f"SELECT name, projection_x, projection_y FROM read_parquet('{parquet.as_posix()}')"
    ).fetchall()
    return {name: (x, y) for name, x, y in rows}


def main() -> int:
    base_parquet = BUILD / "control_A_embedded.parquet"
    if not base_parquet.is_file():
        raise SystemExit(
            f"{base_parquet} is missing — run "
            "`uv run eval/map-refit-stability/measure.py` first to populate build/."
        )

    base_names, base_vectors = load_embeddings(base_parquet)
    print(f"[price] base: {len(base_names)} rows, {base_vectors.shape[1]}-d", file=sys.stderr)

    t0 = time.time()
    reducer = umap.UMAP(
        n_components=2,
        n_neighbors=15,
        min_dist=0.1,
        metric="cosine",
        random_state=42,
        verbose=False,
    )
    base_coords = reducer.fit_transform(base_vectors)
    fit_seconds = time.time() - t0
    print(f"[price] fit in {fit_seconds:.1f}s", file=sys.stderr)

    pickle_path = BUILD / "fitted_reducer.pkl"
    with open(pickle_path, "wb") as f:
        pickle.dump(reducer, f)
    pickle_bytes = pickle_path.stat().st_size
    print(f"[price] pickled reducer: {pickle_bytes:,} bytes", file=sys.stderr)

    # The scale to normalise raw displacement against, matching measure.py's own —
    # the base map's median nearest-neighbour spacing. Reported for completeness;
    # the fidelity claim below is the kNN-overlap number, not this one.
    diff = base_coords[:, None, :] - base_coords[None, :, :]
    dist = np.sqrt((diff**2).sum(axis=-1))
    np.fill_diagonal(dist, np.inf)
    scale = float(np.median(dist.min(axis=1)))

    base_name_set = set(base_names)
    results = {
        "base_rows": len(base_names),
        "umap_params": {"metric": "cosine", "neighbors": 15, "min_dist": 0.1, "seed": 42},
        "fit_seconds": round(fit_seconds, 1),
        "pickled_reducer_bytes": pickle_bytes,
        "base_map_median_nn_spacing": scale,
        "base_rows_moved_by_transform": 0.0,
        "knn_overlap_k": K_NEIGHBOURS,
        "placements": {},
    }

    for tag in APPEND_FRACTIONS:
        embedded = BUILD / f"{tag}_embedded.parquet"
        projected = BUILD / f"{tag}_projected.parquet"
        if not embedded.is_file() or not projected.is_file():
            print(f"[price] skipping {tag}: {embedded} or {projected} missing", file=sys.stderr)
            continue

        all_names, all_vectors = load_embeddings(embedded)
        new_indices = [i for i, n in enumerate(all_names) if n not in base_name_set]
        new_names = [all_names[i] for i in new_indices]
        new_vectors = all_vectors[new_indices]

        t0 = time.time()
        placed = reducer.transform(new_vectors)
        transform_seconds = time.time() - t0

        # Determinism check: transform the same rows twice and confirm agreement,
        # matching the control this card's headline measurement already established
        # for a full refit.
        placed_again = reducer.transform(new_vectors)
        transform_repeat_max_abs_diff = float(np.max(np.abs(placed - placed_again)))

        full_refit_xy = load_xy(projected)
        # The base rows AS THIS FULL REFIT PLACED THEM — its own frame, not the
        # original base fit's. That is the pool a new row's neighbours are drawn
        # from on the "expensive" side of the comparison.
        base_coords_in_full_refit = np.array([full_refit_xy[n] for n in base_names])
        true_new_coords = np.array([full_refit_xy[n] for n in new_names])

        # Frame-invariant fidelity: for each new row, its k nearest BASE rows in the
        # transform's frame (base_coords, placed is in the same frame) against its k
        # nearest BASE rows in the full refit's frame (base_coords_in_full_refit,
        # true_new_coords is in the same frame). Both sides draw neighbours from the
        # identical 3,000-row pool, identified by name, so "overlap" means the same
        # base rows were picked as nearest on both sides regardless of either frame's
        # rotation, reflection or scale.
        k = min(K_NEIGHBOURS, len(base_names))

        def nearest_base_indices(query_coords: np.ndarray, pool_coords: np.ndarray) -> np.ndarray:
            diff = pool_coords[None, :, :] - query_coords[:, None, :]
            dist = np.sqrt((diff**2).sum(axis=-1))
            return np.argsort(dist, axis=1)[:, :k]

        nn_transform = nearest_base_indices(placed, base_coords)
        nn_full_refit = nearest_base_indices(true_new_coords, base_coords_in_full_refit)
        fractions = np.array(
            [
                len(set(nn_transform[i]) & set(nn_full_refit[i])) / k
                for i in range(len(new_names))
            ]
        )

        # Raw displacement is still computed and reported, but see the module
        # docstring: it mixes genuine placement error with the fact that the two
        # frames are unrelated, so it is not the fidelity claim.
        disp = np.sqrt(((placed - true_new_coords) ** 2).sum(axis=1))

        results["placements"][tag] = {
            "new_rows": len(new_names),
            "transform_seconds": round(transform_seconds, 2),
            "transform_repeat_max_abs_diff": transform_repeat_max_abs_diff,
            "knn_overlap_with_full_refit_mean": float(fractions.mean()),
            "knn_overlap_with_full_refit_median": float(np.median(fractions)),
            "raw_displacement_vs_full_refit_mean": float(disp.mean()),
            "raw_displacement_vs_full_refit_normalised_mean": float(disp.mean() / scale),
        }
        print(
            f"[price] {tag}: {len(new_names)} new rows, kNN-overlap fidelity vs a full "
            f"refit = {fractions.mean():.3f} (raw displacement {disp.mean():.3f} — "
            f"cross-frame, see docstring)",
            file=sys.stderr,
        )

    out = HERE / "transform_pricing.json"
    out.write_text(json.dumps(results, indent=2) + "\n")
    print(f"[price] wrote {out}", file=sys.stderr)
    print(json.dumps(results, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
